-- EVShare 3D - Phase 19: Expense Cost Sharing Schema & Seed Migration

CREATE TABLE IF NOT EXISTS expense_shares (
    id CHAR(36) PRIMARY KEY,
    expense_id CHAR(36) NOT NULL,
    user_id CHAR(36) NOT NULL,
    ownership_percentage DECIMAL(7, 4) NOT NULL,
    share_amount DECIMAL(14, 2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ALLOCATED',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_expense_shares_expense FOREIGN KEY (expense_id) REFERENCES expenses (id) ON DELETE CASCADE,
    CONSTRAINT fk_expense_shares_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uk_expense_shares_expense_user UNIQUE (expense_id, user_id),
    INDEX idx_expense_shares_expense (expense_id),
    INDEX idx_expense_shares_user (user_id),
    INDEX idx_expense_shares_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

